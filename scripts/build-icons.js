// Copies only the lucide icons the app uses into public/icons-data.js (so the deployed app doesn't need lucide-static).
// It finds every quoted icon name inside icon(...) calls (ternaries included) and data-icon="name" attributes. Run: npm run icons
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = ['public/app.js', 'public/index.html'].map((f) => fs.readFileSync(path.join(root, f), 'utf8')).join('\n');
const inCalls = [...src.matchAll(/\bicon\(([^()]*)\)/g)].flatMap((m) => [...m[1].matchAll(/['"]([a-z0-9-]+)['"]/g)].map((q) => q[1]));
const names = [...new Set([...inCalls, ...[...src.matchAll(/data-icon="([a-z0-9-]+)"/g)].map((m) => m[1])])].sort();

const dir = path.join(root, 'node_modules/lucide-static/icons');
const out = {};
for (const n of names) {
  const file = path.join(dir, `${n}.svg`);
  if (!fs.existsSync(file)) { console.error(`No lucide icon named "${n}"`); process.exitCode = 1; continue; }
  const svg = fs.readFileSync(file, 'utf8');
  out[n] = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').trim();
}
fs.writeFileSync(path.join(root, 'public/icons-data.js'), `// Generated by scripts/build-icons.js from lucide-static (ISC license). Do not edit.\nconst ICON_PATHS = ${JSON.stringify(out, null, 1)};\n`);
console.log(`${Object.keys(out).length} icons: ${Object.keys(out).join(', ')}`);
